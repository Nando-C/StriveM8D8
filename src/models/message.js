import mongoose from 'mongoose'
import { ensureTtlIndex } from './ttl.js'

export const MESSAGE_KINDS = ['text', 'system', 'call', 'deleted']

const messageSchema = new mongoose.Schema({
    // The id of the conversation this belongs to ("conversationId" on the wire). The
    // field keeps the name it had when conversations were keyed by a pair of usernames.
    conversationKey: { type: String, required: true },
    /** The author's `userId`. */
    from: { type: String, required: true },
    // The author's username when this was sent. The author may later leave, or stop
    // existing; their messages must still say who wrote them.
    fromName: { type: String, required: true },
    kind: { type: String, enum: MESSAGE_KINDS, default: 'text' },
    // Not required by the schema: system and call messages have none. That a text
    // message has something in it is checked where messages are accepted.
    text: String,
    /** Structured content of system and call messages. */
    data: mongoose.Schema.Types.Mixed,
    // Files sent with the message, as a client is told of them (see models/file.js for
    // where they are). A message with attachments may have no text.
    attachments: {
        type: [{
            _id: false,
            id: String, name: String, type: { type: String }, size: Number,
            width: Number, height: Number, durationMs: Number, placeholder: String,
        }],
        default: undefined,
    },
    // Generated by the sending client; absent on messages no client sent.
    clientId: String,
    createdAt: { type: Date, default: Date.now },
})
// Serves "latest N of a conversation" including the _id tie-breaker used when sorting.
messageSchema.index({ conversationKey: 1, createdAt: 1, _id: 1 })

export const Message = mongoose.model('Message', messageSchema)

/** Messages are deleted `ttlHours` after they were sent; 0 or undefined: never. */
export const ensureMessageIndexes = ({ ttlHours } = {}) =>
    ensureTtlIndex(Message, { field: 'createdAt', name: 'message_expiry', ttlHours })
