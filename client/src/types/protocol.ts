// Wire protocol shared with the server (see ../../../src/sockets/index.js and the root README).
//
// These types are a hand-maintained copy, on purpose: the server is plain JavaScript and the
// two packages are independent, so there is no shared-types package. When the server's
// protocol changes, this file changes in the same commit.

export interface OnlineUser {
  username: string
  /** The user's current socket id. Changes every time they reconnect. */
  id: string
}

// ---------- client → server

export interface LoginPayload {
  username: string
  /** Token from a previous `loggedin`, to reclaim the same username after a reconnect. */
  sessionToken?: string
}

export interface SendMessagePayload {
  /** The recipient's current socket id. */
  toUserId: string
  text: string
  /** Generated by this client for each message; comes back in `history`. */
  clientId: string
}

export type SendMessageAck =
  | { ok: true; id: string; timestamp: number }
  | { ok: false; message: string }

export interface GetHistoryPayload {
  withUsername: string
}

// ---------- server → client

export interface LoggedInPayload {
  username: string
  id: string
  /** Private to this client. Never sent to anyone else. */
  sessionToken: string
  /** Everyone online right now, including this user. */
  onlineUsers: OnlineUser[]
}

export interface LoginErrorPayload {
  message: string
}

/** A user came online, or an online user now has a new socket id: upsert by username. */
export interface NewLoginPayload {
  username: string
  id: string
}

export interface UserLeftPayload {
  id: string
}

/** A message delivered live. */
export interface ChatMessage {
  id: string
  from: string
  fromId: string
  text: string
  timestamp: number
}

/**
 * A stored message, as returned by `history`. Deliberately a different type from
 * `ChatMessage`: it has `to` and `clientId` and no `fromId` (socket ids are not stored).
 * The same message has the same `id` in both.
 */
export interface HistoryMessage {
  id: string
  /** `null` for messages that were not sent by a client. */
  clientId: string | null
  from: string
  to: string
  text: string
  timestamp: number
}

export interface HistoryPayload {
  withUsername: string
  /** The most recent 100 messages, oldest first. */
  messages: HistoryMessage[]
}

export interface HistoryErrorPayload {
  /** Echoed from the request, or `null` if the request did not carry a string. */
  withUsername: string | null
  message: string
}

// ---------- event maps for socket.io's typed sockets

export interface ServerToClientEvents {
  loggedin: (payload: LoggedInPayload) => void
  loginError: (payload: LoginErrorPayload) => void
  newLogin: (payload: NewLoginPayload) => void
  userLeft: (payload: UserLeftPayload) => void
  message: (payload: ChatMessage) => void
  history: (payload: HistoryPayload) => void
  historyError: (payload: HistoryErrorPayload) => void
}

export interface ClientToServerEvents {
  login: (payload: LoginPayload) => void
  sendmessage: (payload: SendMessagePayload, ack: (response: SendMessageAck) => void) => void
  getHistory: (payload: GetHistoryPayload) => void
}
